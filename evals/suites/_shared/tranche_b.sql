CREATE TYPE user_status AS ENUM ('active', 'inactive');

CREATE TABLE teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    nickname TEXT,
    status user_status NOT NULL DEFAULT 'active',
    code VARCHAR(20) NOT NULL,
    legacy TEXT,
    team_id INTEGER
);

CREATE TABLE orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    reference TEXT NOT NULL,
    CONSTRAINT orders_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_orders_reference ON orders(reference);
CREATE INDEX idx_active_user_email ON users(email) WHERE status = 'active';

CREATE TABLE sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    token TEXT NOT NULL
);

CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL
);

CREATE VIEW user_directory AS
SELECT id, email, status FROM users;

CREATE VIEW active_user_directory AS
SELECT id, email FROM user_directory WHERE status = 'active';

CREATE MATERIALIZED VIEW product_summary AS
SELECT id, name, price FROM products;

CREATE VIEW product_rollup AS
SELECT id, price FROM product_summary;

CREATE SEQUENCE ticket_id_seq START WITH 1;

CREATE TABLE tickets (
    id INTEGER PRIMARY KEY DEFAULT nextval('ticket_id_seq'),
    title TEXT NOT NULL
);

CREATE TABLE items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    quantity INTEGER NOT NULL
);

CREATE FUNCTION validate_item_quantity() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.quantity < 0 THEN
        RAISE EXCEPTION 'quantity must be non-negative';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER items_quantity_check
BEFORE UPDATE ON items
FOR EACH ROW EXECUTE FUNCTION validate_item_quantity();

CREATE TABLE feature_flags (
    name TEXT PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE empty_options (
    id INTEGER PRIMARY KEY,
    value TEXT
);

