"""Data model for the eval harness.

Deliberately reuses schemint's own vocabulary rather than inventing a third
one: ``RiskLevel`` matches ``change_classifier``/``SchemaChangeEvent`` and
``Severity`` matches ``AgentDecision``. Every number a scorer produces should
map back to a line of production code without a translation table.

Four things travel through the harness:

    EvalTask       what to run (inputs, committed)
    Truth          what actually happened in Postgres (generated, committed)
    EvalAnalysis   what the system under test said (measured, stored)
    ScoreRow       how the two compare (derived, stored)
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from typing import Any, Literal

from pydantic import BaseModel, Field

# =============================================================================
# Vocabulary — mirrors schemint's own Literals
# =============================================================================

# schemint.drift.models.SchemaChangeEvent.change_risk
RiskLevel = Literal["safe", "needs_review", "potentially_breaking", "breaking"]

# schemint.drift.models.AgentDecision.severity
Severity = Literal["low", "medium", "high", "critical"]

TaskCategory = Literal["breaking", "safe", "subtle", "adversarial", "ambiguous"]

# For ambiguous tasks the correct behaviour is to ask a human, not to land on a
# particular risk level — they are scored on escalation only.
ExpectedOutcome = Literal["classify", "escalate"]

RISK_ORDER: tuple[RiskLevel, ...] = (
    "safe",
    "needs_review",
    "potentially_breaking",
    "breaking",
)

SEVERITY_ORDER: tuple[Severity, ...] = ("low", "medium", "high", "critical")

# The boundary schemint itself uses to gate a migration: anything at or above
# potentially_breaking is treated as "this can break consumers".
BREAKING_THRESHOLD: RiskLevel = "potentially_breaking"


def risk_index(risk: str) -> int:
    """Ordinal position of a risk level; unknown values sort as ``safe``."""
    try:
        return RISK_ORDER.index(risk)  # type: ignore[arg-type]
    except ValueError:
        return 0


def severity_index(severity: str) -> int:
    """Ordinal position of a severity; unknown values sort as ``low``."""
    try:
        return SEVERITY_ORDER.index(severity)  # type: ignore[arg-type]
    except ValueError:
        return 0


def max_risk(risks: list[str]) -> RiskLevel:
    """Highest risk level in the list; ``safe`` when empty."""
    if not risks:
        return "safe"
    return RISK_ORDER[max(risk_index(r) for r in risks)]


def is_breaking(risk: str) -> bool:
    """Whether a risk level counts as breaking for classification metrics."""
    return risk_index(risk) >= risk_index(BREAKING_THRESHOLD)


# =============================================================================
# Task definition (committed, hand-written)
# =============================================================================


class EvalTask(BaseModel):
    """One migration scenario.

    Mirrors ``evals/suites/<id>/meta.json`` plus the resolved directory. The
    SQL files are read lazily by the oracle and the adapters — they are not
    carried in the model, so a suite listing stays cheap.
    """

    id: str
    category: TaskCategory
    notes: str = ""
    expected_outcome: ExpectedOutcome = "classify"
    # Baseline schema shared across tasks, relative to evals/suites/. When set,
    # schema.sql in the task directory is skipped in favour of this file.
    shared_schema: str | None = None
    # Resolved at load time, not stored in meta.json.
    directory: str = ""


# =============================================================================
# Ground truth (generated by the oracle, committed)
# =============================================================================


class ObjectHealth(BaseModel):
    """Whether one database object was usable at a point in time.

    ``ok=False`` before the migration means the object was already broken —
    those are excluded from blast radius, which is what the oracle's pre-pass
    exists to establish.
    """

    key: str
    ok: bool
    detail: str = ""


class HealthReport(BaseModel):
    """Result of probing every dependent object in a database."""

    objects: list[ObjectHealth] = Field(default_factory=list)
    row_counts: dict[str, int] = Field(default_factory=dict)

    def by_key(self) -> dict[str, ObjectHealth]:
        return {obj.key: obj for obj in self.objects}

    def healthy_keys(self) -> set[str]:
        return {obj.key for obj in self.objects if obj.ok}


class Truth(BaseModel):
    """What actually happened when the migration hit a real database.

    Mechanically generated — never hand-written. ``generator_version`` is
    stamped on every artefact so a change to the severity rule table forces
    regeneration and produces a reviewable diff.
    """

    task_id: str
    generator_version: str
    # Hash of meta/schema/seed/migration/probe inputs. This is a portable
    # freshness check; filesystem mtimes are not preserved by Git checkouts.
    input_hash: str = ""
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    # Did the migration statement itself fail?
    migration_error: str | None = None

    risk: RiskLevel
    must_block: bool
    # Keys (see evals.core.keys) that worked before and did not after.
    blast_radius: list[str] = Field(default_factory=list)
    # table -> number of rows lost. Populated only when a count decreased.
    rows_lost: dict[str, int] = Field(default_factory=dict)

    # Which rule in evals/oracle/rules.py fired, for auditability.
    rule_fired: str = ""

    # SchemaSnapshot.model_dump() before and after, from LiveDBSnapshotCapture.
    # The post snapshot is what makes simulator-fidelity scoring possible; the
    # pre snapshot is the target a rollback has to restore.
    real_pre_snapshot: dict[str, Any] | None = None
    real_post_snapshot: dict[str, Any] | None = None

    @property
    def migration_failed(self) -> bool:
        return self.migration_error is not None


# =============================================================================
# System-under-test output (measured)
# =============================================================================


class EvalAnalysis(BaseModel):
    """Normalized output of one adapter on one task.

    ``is_breaking`` is deliberately absent — it is derived from ``risk`` so the
    two can never disagree.
    """

    risk: RiskLevel = "safe"
    # Only the drift-pipeline adapter produces a severity; the sandbox
    # adapters have no equivalent field.
    severity: Severity | None = None
    blast_radius: list[str] = Field(default_factory=list)
    blocked: bool = False
    safety_score: int | None = None
    rationale: str = ""

    # AI artefacts, graded by their own scorers against a live database.
    rollback_sql: str | None = None
    alternative_sqls: list[str] = Field(default_factory=list)

    # AlterApplier's predicted post-migration SchemaSnapshot, compared against
    # Truth.real_post_snapshot by the fidelity scorer.
    predicted_snapshot: dict[str, Any] | None = None

    # Metering
    tokens_in: int = 0
    tokens_out: int = 0
    cache_read_tokens: int = 0
    cache_write_tokens: int = 0
    llm_calls: int = 0
    cost_usd: float = 0.0
    latency_ms: int = 0

    # Set when the adapter raised. A run with an error still produces a row so
    # failures stay visible in the results table rather than vanishing.
    error: str | None = None

    @property
    def is_breaking(self) -> bool:
        return is_breaking(self.risk)


# =============================================================================
# Run configuration
# =============================================================================


class RunConfig(BaseModel):
    """Everything that could change an adapter's answer.

    ``config_hash`` covers all of it, so editing a prompt or bumping the
    generator automatically separates the new results from the old rather than
    silently mixing them in the same bucket.
    """

    adapter: str
    adapter_version: str = "1"
    model_id: str = "none"
    # sha256 of the prompt constant(s) the adapter uses, truncated.
    prompt_version: str = "none"
    # None means the parameter was not sent (required on models that reject it).
    temperature: float | None = None
    # Repeat index. The Anthropic API has no seed parameter — trials measure
    # sampling variance, they do not reproduce it.
    trial: int = 0
    # Ties results to the ground truth they were scored against.
    generator_version: str = "unknown"

    def config_hash(self) -> str:
        """Stable hash of everything except ``trial``.

        Trials of the same configuration share a hash so they aggregate
        together; anything else that differs splits them apart.
        """
        payload = {
            "adapter": self.adapter,
            "adapter_version": self.adapter_version,
            "model_id": self.model_id,
            "prompt_version": self.prompt_version,
            "temperature": self.temperature,
            "generator_version": self.generator_version,
        }
        encoded = json.dumps(payload, sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(encoded.encode("utf-8")).hexdigest()[:16]

    def label(self) -> str:
        """Short human-readable identity for report tables."""
        if self.model_id == "none":
            return self.adapter
        return f"{self.adapter}@{self.model_id}"


# =============================================================================
# Scoring
# =============================================================================


class ScoreRow(BaseModel):
    """One (task, config, trial) scored against truth.

    ``underestimated`` is the safety metric: predicted risk below true risk on
    a breaking task is a P0 regardless of what F1 says.
    """

    task_id: str
    category: TaskCategory
    adapter: str
    config_hash: str
    trial: int

    # Breaking / not-breaking classification
    true_breaking: bool
    pred_breaking: bool
    correct: bool
    false_positive: bool
    false_negative: bool

    # Risk level
    risk_exact_match: bool
    underestimated: bool
    overestimated: bool

    # Blast radius (1.0 when both sides are empty — nothing to find, nothing
    # invented)
    blast_recall: float = 1.0
    blast_precision: float = 1.0
    blast_f1: float = 1.0
    blast_true_count: int = 0
    blast_pred_count: int = 0

    blocked_correctly: bool = False

    # Set only by the scorers that need a live database; None means not run.
    fidelity_pct: float | None = None
    rollback_executes: bool | None = None
    rollback_restores: bool | None = None
    injection_resisted: bool | None = None

    cost_usd: float = 0.0
    latency_ms: int = 0
    errored: bool = False
